function filtro = fx_nlms(filtro)

% Read data input

s = filtro.s;                 % Acoustic estimate paths
in = filtro.x;                % Reference signals
e = filtro.e;                  % Error signals

buffL = filtro.buffL;         % buffer for store the rference filtered signal
buffS = filtro.buffS;         % Buffer for filtering the reference signal by the estimate paths
w = filtro.w;                 % Adaptive coefficients
mu = filtro.mu;               % Step size

L = size(w,1);                % Number of filter coefficients
[~,I] = size(in);             % Number of reference signals
[~,J,K] = size(s);            % Number of actuators (J) and error sensor (K)
[N,~] = size(in);             % Size of block (TamB)


e = reshape(e,N,K);     % Reshape e into N by K matrix


% 1 Generate the outputs
y = zeros(N,J);               % Variable for the signal to be generated by each of the adaptive filters in each iteration.

for sec = 1:J
    for ref = 1:I
       [yj,filtro.state_w(:,sec,ref)] = filter(filtro.w(:,ref,sec),1,filtro.x(:,ref),filtro.state_w(:,sec,ref));
        y(:,sec)=y(:,sec)+yj;
    end
end

% 2 Update coefficients

for n=1:N
    for nref = 1:I
        for nsec = 1:J
            paso = zeros(L,1);
            for nmic = 1:K
                paso = paso+buffL((N-n)+[1:L],nref,nsec,nmic)*e(n,nmic);
            end
            w(:,nref,nsec) = w(:,nref,nsec)-2*mu*paso;
        end
    end
end

% 3 Filter the reference signal

for nref = 1:I
    for nsec = 1:J
        for nmic = 1:K

            [vijk(:,nref,nsec,nmic),buffS(:,nref,nsec,nmic)] = filter(s(:,nsec,nmic),1,in(:,nref),buffS(:,nref,nsec,nmic));
        end
    end
end

buffL = [vijk(end:-1:1,:,:,:);buffL(1:L-1,:,:,:)];


% Update the field of the objects
filtro.y = y;
filtro.w = w;
filtro.buffL = buffL;
filtro.buffS = buffS;
end
