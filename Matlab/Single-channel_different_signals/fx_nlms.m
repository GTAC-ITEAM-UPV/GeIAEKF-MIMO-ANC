function filtro = fx_nlms(filtro)

s=filtro.s;
in=filtro.x;
e=filtro.e;
buffL=filtro.buffL;
buffS=filtro.buffS;
w=filtro.w;
epsilon = filtro.epsilon;
mu=filtro.mu;

[N,I] = size(in);             % Number of reference signals, I, Size of block (TamB), N
[A,J,K] = size(s);            % Number of actuators (J) and error sensor (K)
[L,~,~] = size(w);            % Number of filter coefficients
w=w(:);

% 1 Generate the outputs
y = zeros(N,J);               % Variable for the signal to be generated by each of the adaptive filters in each iteration.

for sec = 1:J
    for ref = 1:I
        [yj,filtro.state_w(:,ref,sec)] = filter(w(:,ref,sec),1,in(:,ref),filtro.state_w(:,ref,sec));
        y(:,sec)=y(:,sec)+yj;
    end
end

% 2 Start NLMS algorithm
for n=1:N

    for nref=1:I

        for nsec=1:J
            paso=zeros(L,1);
            for nmic=1:K
                paso=paso+buffL((N-n)+[1:L],nref,nsec,nmic)*e(n,nmic);
            end
            %p = norm(buffL)^2 + epsilon;
            p = 1;
            w(:,nref,nsec)=w(:,nref,nsec)-2*mu*paso/p;
        end
    end

end

% 3 Filter the reference signal

for nref=1:I
    for nsec=1:J
        for nmic=1:K
            [vijk(:,nref,nsec,nmic),buffS(:,nref,nsec,nmic)]=filter(s(:,nsec,nmic),1,in(1:N,nref),buffS(:,nref,nsec,nmic));
        end
    end
end

buffL=[-vijk(end:-1:1,:,:,:);filtro.buffL(1:L-1,:,:,:)];





% Update the field of the objects
filtro.w = w;
filtro.e = e;
filtro.y = y;
filtro.buffL=buffL;
filtro.buffS=buffS;



end