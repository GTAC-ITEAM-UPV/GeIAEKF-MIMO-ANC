function filtro = fx_geiaekf(filtro)

% Read data input

w = filtro.w;                 % Adaptive coefficients
P = filtro.P_n1;              % Covariance of the coefficients
F = filtro.F_n;               % State transition matrix
Q_n = filtro.Q_n;             % Covariance of process noise

% Extraction of signals and system involved in the algorithm
s = filtro.s;                 % Acoustic estimate paths
in = filtro.x;                % Reference signals
e = filtro.e;                 % Error signals
y = filtro.y;
%d = filtro.d;
H_n = filtro.buffL;           % Buffer for store the reference filtered signal
buffS = filtro.buffS;         % Buffer for filtering the reference signal by the estimate paths

[N,I] = size(in);             % Number of reference signals, I, Size of block (TamB), N
[A,J,K] = size(s);            % Number of actuators (J) and error sensor (K)
[L,~,~] = size(w);            % Number of filter coefficients
w=w(:);
buffe = filtro.buffe;
M = filtro.M;                 % Window size
C = filtro.C;                 % Variance-covariance matrix
xp=zeros(L,N,I,J,K);
for dim=1:N
    xp(:,dim,:,:,:)=[H_n(N-dim+(1:L),:,:,:)];
end

% Reorder measure matrix into a 2D matrix of size (IJLxKN)
H = zeros(I*J*L,K*N);
for i=1:I
    for j=1:J
        for k=1:K
            x(1+L*(i-1)+L*I*(j-1):i*L+L*I*(j-1),1+N*(k-1):N*k)=xp(:,:,i,j,k);
        end
    end
end


% 1 Generate the outputs
y = zeros(N,J);               % Variable for the signal to be generated by each of the adaptive filters in each iteration.

for sec = 1:J
    for ref = 1:I
       [yj,filtro.state_w(:,ref,sec)] = filter(filtro.w(:,ref,sec),1,filtro.x(:,ref),filtro.state_w(:,ref,sec));
        y(:,sec)=y(:,sec)+yj;
    end
end

% 2 Start Kalman Algorithm

% Prediction
    wp = w;
    Pp = P+Q_n;

% Compute Variance-Covariance matrix C
    buffe = [e*e';buffe(1:M-1)];
    C =  mean(buffe) + filtro.epsilon;

    % out = buffe(M);
    % buffe = [e*e';buffe(1:M-1)];
    % %C =  mean(buffe);
    % C = C + (buffe(1)-out)/M;
    % if C < filtro.epsilon
    %     C = C + filtro.epsilon;
    % end

% Kalman Gain Calculation

    Z = Pp*x;
    Kg = Z/C;

% % Error Calculation
% e = xp+x*wp;

% Update


z = filtro.mu*Kg*e;
w = wp +z;
w = reshape(w,[L,I,J]);
filtro.P_n1= Pp - Z*Kg';

% 3 Filter the reference signal

for nref=1:I
    for nsec=1:J
        for nmic=1:K
          [vijk(:,nref,nsec,nmic),buffS(:,nref,nsec,nmic)]=filter(s(:,nsec,nmic),1,in(1:N,nref),buffS(:,nref,nsec,nmic));  
        end
    end
end

buffL=[-vijk(end:-1:1,:,:,:);filtro.buffL(1:L-1,:,:,:)];

% Tuning Q and R
beta=0.9999;
Q_n = beta*Q_n+(1-beta)*diag((z).^2);



% Update the field of the objects
filtro.w = w;
filtro.e = e;
filtro.y = y;
filtro.buffL = buffL;
filtro.buffS = buffS;
filtro.buffe = buffe;
filtro.Q_n = Q_n;
end